/**
 * The 20 curated demonstration patients.
 *
 * Written as data rather than code so the roster is reviewable by a clinician who
 * does not read JavaScript. Each case carries an `expect` block naming the ESI it
 * should land on and the rule that should get it there — the seeder checks the
 * live system against those expectations and reports any that miss, so this file
 * doubles as an end-to-end regression suite over the whole pipeline.
 *
 * Data completeness is chosen per patient, not applied uniformly. That is the
 * point of several of these cases: the low-acuity patients have full observations
 * and a prior record precisely so the assistant can be confident enough to leave
 * them at ESI 4 or 5, while the ambiguous ones are deliberately thin, and the
 * system's caution about them is the behaviour being demonstrated.
 */

